import { PrismaClient } from '@prisma/client';

declare global {
  // Allow global prisma for dev to prevent hot reload issues
  var prisma: PrismaClient | undefined;
}

export const prisma =
  global.prisma ||
  new PrismaClient({
    log: ['error', 'warn'],
  });

if (process.env.NODE_ENV !== 'production') {
  global.prisma = prisma;
}